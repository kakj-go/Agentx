import { expect, type Browser, type Locator, type Page, test } from '@playwright/test'

const company = 'Agentx E2E'
const adminPassword = 'agentx-e2e-admin-password'

async function dialog(page: Page, title: string) {
  const value = page.getByRole('dialog', { name: title })
  await expect(value).toBeVisible()
  return value
}

async function field(container: Locator, label: string) {
  return container.locator('label').filter({ hasText: label }).locator('input, textarea').first()
}

async function select(container: Locator, label: string, option: string) {
  await container.getByRole('combobox', { name: label, exact: true }).click()
  await container.page().getByRole('option', { name: option, exact: true }).click()
}

async function submit(container: Locator, name: string) {
  await container.getByRole('button', { name, exact: true }).click()
  await expect(container).toBeHidden()
}

async function fillMonaco(page: Page, scope: Locator, value: string) {
  const editor = scope.getByRole('textbox', { name: 'Editor content' })
  await expect(editor).toBeVisible({ timeout: 30_000 })
  await editor.focus()
  await page.keyboard.press('Control+A')
  await page.keyboard.press('Backspace')
  await page.keyboard.insertText(value)
  await expect.poll(async () => {
    const text = (await scope.locator('.view-lines').textContent())?.replaceAll('\u00a0', ' ').trim()
    try { return JSON.parse(text ?? '') } catch { return null }
  }).toEqual(JSON.parse(value))
}

async function grantResource(page: Page, name: string, resourceType: string, subject: 'workflow' | 'department', operation = '使用') {
  await page.getByRole('tab', { name: resourceType, exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: name }).filter({ hasText: resourceType }).first()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: '管理授权' }).click()
  const grant = page.getByRole('dialog', { name: new RegExp(`管理.*${name}.*授权`) })
  await expect(grant).toBeVisible()
  if (subject === 'department') {
    await select(grant, '授权对象类型', '部门')
    await select(grant, '授权对象', company)
  } else {
    await select(grant, '授权对象类型', 'Workflow 运行身份')
    await select(grant, '授权对象', 'MCP Echo Workflow')
  }
  await select(grant, '操作', operation)
  await grant.getByRole('button', { name: '添加授权' }).click()
  await expect(grant.getByRole('button', { name: '撤销授权' })).toHaveCount(1)
  await grant.getByRole('button', { name: '取消' }).click()
  await expect(grant).toBeHidden()
}

