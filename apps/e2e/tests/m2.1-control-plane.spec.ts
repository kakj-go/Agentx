async function configureAndPublishWorkflow(page: Page) {
  await page.getByRole('link', { name: /^工作流/ }).click()
  await page.getByRole('row', { name: /MCP Echo Workflow/ }).getByRole('link', { name: '打开画布' }).click()
  await expect(page.getByTestId('workflow-canvas')).toBeVisible()
  await page.getByTestId('palette-action-mcp_tool').click()
  const toolNode = page.locator('.react-flow__node-manifest').filter({ hasText: /mcp tool/i }).first()
  await expect(toolNode).toBeVisible()
  const resource = page.getByTestId('resource-selector-mcp_tool').getByRole('combobox')
  await resource.click()
  await page.getByRole('option', { name: /echo/ }).click()
  await fillMonaco(page, page.getByTestId('parameter-arguments'), '{"text":"Agentx E2E"}')
  const source = page.locator('.react-flow__node').filter({ hasText: 'Manual Trigger' }).first().locator('.react-flow__handle.source[data-handleid="main"]')
  const target = toolNode.locator('.react-flow__handle.target[data-handleid="main"]')
  await expect(source).toBeVisible()
  await expect(target).toBeVisible()
  const sourceBox = await source.boundingBox()
  const targetBox = await target.boundingBox()
  if (!sourceBox || !targetBox) throw new Error('Workflow node handles are not visible')
  await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(targetBox.x + targetBox.width / 2, targetBox.y + targetBox.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.locator('.react-flow__edge')).toHaveCount(1)
  const save = page.getByRole('button', { name: '保存', exact: true })
  const draftRequest = page.waitForRequest((request) => request.method() === 'PUT' && /\/workflows\/[^/]+\/draft$/.test(request.url()))
  await save.click()
  const payload = (await draftRequest).postDataJSON() as { definition: { nodes: Array<{ type: string; parameters: Record<string, unknown> }> } }
  expect(payload.definition.nodes.find((node) => node.type === 'mcp_tool')?.parameters).toEqual({ arguments: { text: 'Agentx E2E' } })
  await expect(page.getByRole('status').filter({ hasText: /mcp_server .* requires use grant/i })).toBeVisible()

  const grantsPage = await page.context().newPage()
  await grantsPage.goto('/resource-grants')
  await expect(grantsPage.getByRole('heading', { name: '资源授权' })).toBeVisible()
  await grantResource(grantsPage, 'Echo MCP', 'MCP Server', 'workflow')
  await grantsPage.close()

  await save.click()
  await expect(page.locator('header').getByText(/Revision \d+ · 已保存/)).toBeVisible({ timeout: 30_000 })
  await page.getByRole('link', { name: '返回', exact: true }).click()
  await expect(page.getByText('资源与授权校验通过')).toBeVisible()
  await page.getByRole('button', { name: '创建版本' }).click()
  await expect(page.getByText('v1', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: '发布', exact: true }).first().click()
  const publish = await dialog(page, '发布')
  await select(publish, '选择环境', 'Development')
  await select(publish, '选择版本', 'v1')
  await submit(publish, '发布')
  await expect(page.getByText(/Development · v1/)).toBeVisible()
}

